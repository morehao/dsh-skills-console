/** 按 locale 取文案；缺键先回落中文，再回落键名。 */
export function buildTranslate(locale) {
  const active = () => {
    try {
      return locale?.getLocale?.().active || 'zh';
    } catch {
      return 'zh';
    }
  };
  return (key) => {
    const id = active();
    const pack = DICT[id] || DICT.zh;
    return pack[key] ?? DICT.zh[key] ?? key;
  };
}
